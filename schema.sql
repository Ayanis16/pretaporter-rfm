-- ============================================================
-- PretAPorter RFM - Schema + Data
-- ============================================================

CREATE DATABASE IF NOT EXISTS pretaporter_db CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE pretaporter_db;

SET FOREIGN_KEY_CHECKS = 0;

DROP TABLE IF EXISTS segments_rfm;
DROP TABLE IF EXISTS commandes_produits;
DROP TABLE IF EXISTS commandes;
DROP TABLE IF EXISTS produits;
DROP TABLE IF EXISTS categories;
DROP TABLE IF EXISTS clients;

SET FOREIGN_KEY_CHECKS = 1;

-- Table clients
CREATE TABLE clients (
    client_id       INT AUTO_INCREMENT PRIMARY KEY,
    nom             VARCHAR(100) NOT NULL,
    prenom          VARCHAR(100) NOT NULL,
    email           VARCHAR(255) NOT NULL UNIQUE,
    genre           ENUM('H','F') NOT NULL,
    ville           VARCHAR(100) NOT NULL,
    date_inscription DATE NOT NULL
) ENGINE=InnoDB;

-- Table categories
CREATE TABLE categories (
    categorie_id    INT AUTO_INCREMENT PRIMARY KEY,
    nom             VARCHAR(100) NOT NULL UNIQUE,
    description     TEXT
) ENGINE=InnoDB;

-- Table produits
CREATE TABLE produits (
    produit_id      INT AUTO_INCREMENT PRIMARY KEY,
    nom             VARCHAR(200) NOT NULL,
    categorie_id    INT NOT NULL,
    genre           ENUM('homme','femme','mixte') NOT NULL DEFAULT 'mixte',
    prix            DECIMAL(10,2) NOT NULL,
    stock           INT NOT NULL DEFAULT 0,
    FOREIGN KEY (categorie_id) REFERENCES categories(categorie_id)
) ENGINE=InnoDB;

-- Table commandes
CREATE TABLE commandes (
    commande_id     INT AUTO_INCREMENT PRIMARY KEY,
    client_id       INT NOT NULL,
    date_commande   DATETIME NOT NULL,
    statut          ENUM('livree','en_cours','annulee') NOT NULL DEFAULT 'en_cours',
    FOREIGN KEY (client_id) REFERENCES clients(client_id)
) ENGINE=InnoDB;

-- Table liaison many-to-many commandes <-> produits
CREATE TABLE commandes_produits (
    commande_id     INT NOT NULL,
    produit_id      INT NOT NULL,
    quantite        INT NOT NULL DEFAULT 1,
    prix_unitaire   DECIMAL(10,2) NOT NULL,
    PRIMARY KEY (commande_id, produit_id),
    FOREIGN KEY (commande_id) REFERENCES commandes(commande_id),
    FOREIGN KEY (produit_id)  REFERENCES produits(produit_id)
) ENGINE=InnoDB;

-- Table résultats RFM (remplie par le script Python)
CREATE TABLE segments_rfm (
    segment_id      INT AUTO_INCREMENT PRIMARY KEY,
    client_id       INT NOT NULL UNIQUE,
    recence         INT NOT NULL COMMENT 'Jours depuis la dernière commande livrée',
    frequence       INT NOT NULL COMMENT 'Nombre de commandes livrées',
    montant         DECIMAL(10,2) NOT NULL COMMENT 'Chiffre d affaires total',
    score_r         INT NOT NULL COMMENT 'Score Récence 1-5',
    score_f         INT NOT NULL COMMENT 'Score Fréquence 1-5',
    score_m         INT NOT NULL COMMENT 'Score Montant 1-5',
    score_rfm       VARCHAR(10) NOT NULL COMMENT 'Concat ex: 555',
    segment         VARCHAR(50) NOT NULL,
    region          VARCHAR(100),
    date_calcul     DATETIME DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (client_id) REFERENCES clients(client_id)
) ENGINE=InnoDB;

